"""Export a fitted strategy as a folder (and a ZIP) that runs on its own, outside the notebook.

Bundle layout:

    strategy.py              two pure functions: predict_returns and target_weights (generated, see below)
    model.joblib             the fitted model
    config.json              the StrategyConfig, as a plain dictionary
    feature_names.json       the model's feature columns, in order
    manifest.json            provenance: versions, creation time, symbols, reference-or-own knobs
    run_paper.py             the paper-trading runner (a copy)
    README_EXPORT.md         step-by-step instructions for running it at home
    requirements.txt         what to pip install (scikit-learn pinned to the version that fitted the model)
    .env.example             where the PAPER keys go (empty; the real .env is never exported)
    quantsoc_ml/             a copy of this package, so strategy.py computes features with the same code
    data/prices_recent.csv.gz  the last days of the committed snapshot, for the offline demo

strategy.py does not re-implement anything: it calls quantsoc_ml.features.build_features with
the strategy's own feature list and portfolio.weights_from_forecasts, exactly as the research
pipeline did. tests/test_export_paper.py checks that its forecasts equal models.predict_panel's.

Credentials are never written. `.env` is never copied, every text file is scanned for
key-shaped strings, and if APCA keys are set in this process's environment the whole bundle is
scanned for their values (bytes, not just text) before the export is accepted.
"""
from __future__ import annotations

import importlib.util
import json
import os
import re
import shutil
import sys
import types
import zipfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence, Union

import pandas as pd

from . import __version__
